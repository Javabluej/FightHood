export function resolveMove(
  type: 'punch' | 'kick' | 'grab',
  crouching: boolean,
  forward: boolean,
  airborne: boolean = false
): string {
  if (type === 'grab') return 'grab';
  if (airborne) {
    return type === 'punch' ? 'airPunch' : 'airKick';
  }
  if (crouching) {
    return type === 'punch' ? 'lowJab' : 'sweep';
  }
  if (forward) {
    return type === 'punch' ? 'special1' : 'special2';
  }
  return type === 'punch' ? 'jab' : 'kick';
}

export function getMoveTotalFrames(move: CombatMove): number {
  return move.startup + move.active + move.recovery;
}

